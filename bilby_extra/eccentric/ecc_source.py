## Two Surrogate functions:
 # Evaluate the fits at requested parameter
 # Evaluate the empirical interpolant using the fit evaluations to
 # estimate the BesselJ function at the requested nu parameter

def evalSurrogate_a(param):
    fit_evals = np.array([f(param) for f in fits_a])
    return np.dot(fit_evals, eim_a_B)


def evalSurrogate_p(param):
    fit_evals = np.array([f(param) for f in fits_p])
    return np.dot(fit_evals, eim_p_B)

def strain_hphc_from_ml_eccentric_model(time_array, total_mass, mass_ratio, spin1z, spin2z, eccentricity,
                                        luminosity_distance, theta_jn, phase, geocent_time, **waveform_arguments):

    delta_t = time_array[1] - time_array[0]

    ##### Since we know the surrogate does work for 65Msun, let's generate waveforms for this mass and then re-scale
    Mtot_nodim = total_mass / 65
    dL_nodim = luminosity_distance / 100

    mass_1 = 65 * mass_ratio / (1+mass_ratio)
    mass_2 = 65 - mass_1

    scale = Mtot_nodim / dL_nodim
    amp = evalSurrogate_a([mass_1, mass_2, spin1z, spin2z, eccentricity])
    phi = evalSurrogate_p([mass_1, mass_2, spin1z, spin2z, eccentricity])
    h22 = scale * amp * np.exp(1j*phi)

    # The waveform is generated by default at 4096Hz, which may be way higher than what we want. Therefore we resample.
    geometric_time_axis = np.arange(0, 1, 1/4096) * Mtot_nodim
    hinterp = interp1d(geometric_time_axis, h22)
    # The resampled_time_axis starts with 0, ends with Mtot_nodim * (1 - 1/4096)
    resampled_time_axis = np.arange(0, Mtot_nodim * 4095/4096, delta_t)
    h22s = hinterp(resampled_time_axis)
    h2m2s = np.conjugate(h22s)

    H = Ydirect(theta_jn, phase, 2,  2)*h22s +\
        Ydirect(theta_jn, phase, 2, -2)*h2m2s

    # Determine length of waveform segment to retain
    template_max_index = np.argmax(np.abs(h22s))
    template_max_time = resampled_wfm_time[template_max_index]
    gps_index = np.argmin(np.abs(time_array - geocent_time))

    t_start = waveform_arguments.get('t_start', None)
    template_start_idx = max(template_max_index - gps_index, 0) \
                         if t_start is not None else \
                         np.argmin(np.abs(resampled_wfm_time - (template_max_time + t_start)))

    max_post_merger = waveform_arguments.get('max_post_merger', None)
    if max_post_merger is not None:
        tmp_end_idx = np.argmin(np.abs(resampled_wfm_time - (template_max_time + max_post_merger)))
        # plus 1 index to match when max_post_merger is longer than the waveform tail
        template_end_idx = min(tmp_end_idx + 1, len(hp))
    else:
        # Take the shorter of the two:
        # Time_array tail length: len(time_array) - gps_index
        # Waveform tail length:   len(hp) - template_max_index
        template_end_idx = min(len(time_array) - gps_index + template_max_index, len(H))
    template_length = template_end_idx - template_start_idx
    # peak_to_start_len = template_max_index - template_start_idx

    # Initialise the final output waveform
    ta_len = len(time_array)
    H_output = np.zeros(ta_len, dtype=complex)
    # Place the waveform segment at the beginning of the output array
    H_output[:template_length] = H[template_start_idx : template_end_idx]
    # Apply tukey window to 1/3 of pre merger
    duration = time_array[-1] - time_array[0]
    alpha = (template_max_index - template_start_idx) * delta_t / duration * (2/3)
    # (max - start) * delta_t / 2 / (time_array[-1] / 2)
    window = tukey(ta_len, alpha=alpha)
    H_output = H_output * window

    # (temp_max_index - temp_start_idx) is the new peak idx after trimming the starting segment
    gt0 = waveform_arguments.get('gt0', True)
    gps_idx = 0 if gt0 else gps_index
    shift =  gps_idx - (template_max_index - template_start_idx)
    # Shift the waveform to the appropriate position
    if shift != 0:
        H_output = rolling(H_output, shift)

    return {'plus': H_output.real, 'cross': H_output.imag}


